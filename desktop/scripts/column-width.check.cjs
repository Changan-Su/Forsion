// Real note columns: hover, pointer preview/commit/cancel, persistence, keyboard and touch.
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
const { chromium } = require('playwright-core')
const { findChromium } = require('./lib/find-chromium.cjs')
const origin = process.env.HARNESS_URL || 'http://localhost:5173/harness.html'
const out = process.env.SHOT_DIR || '/tmp/forsion-column-width-a'
const checks = [], errors = []
fs.mkdirSync(out, {recursive:true})
const ok = (name, value) => { assert.ok(value,name); checks.push(name); console.log('PASS',name) }
const sleep = p => p.waitForTimeout(250)
const seed = (n=2, empty=false) => {
 const columns=Array.from({length:n},(_,i)=>({refs:['col'+i],width:1}))
 return '---\namadeus_schema: amadeus.page/4\namadeus_layout: '+JSON.stringify({v:4,rows:[{columns,tail:'coltail'}]})+'\n---\n# Sampling study\n\n'+columns.map((c,i)=>`<!-- a ${c.refs[0]} -->\n\n`+(empty&&i===1?'':`Column ${i+1}: ${['Methods','Results','Discussion'][i]}\n\n${('Sample size and measurement uncertainty. ').repeat(i===0?8:3)}\n\n`)).join('')+'<!-- a coltail -->\n\nAfter columns.\n'
}
const widths = p => p.evaluate(()=>{let row;window.__upage.probe.view().state.doc.descendants(n=>{if(n.type.name==='amadeusColumnRow')row=n});return row?Array.from({length:row.childCount},(_,i)=>row.child(i).attrs.width):[]})
const grow = p => p.locator('.amx-ucolcell').evaluateAll(es=>es.map(e=>Number(getComputedStyle(e).flexGrow)))
const near = (a,b) => a.length===b.length&&a.every((x,i)=>Math.abs(x-b[i])<.001)
let fixture=0
async function load(p,n=2,empty=false){await p.evaluate(({name,md})=>window.__upage.switchFile(name,md),{name:`Columns-${++fixture}.md`,md:seed(n,empty)});await p.waitForFunction(n=>document.querySelectorAll('.amx-ucolcell').length===n,n);await sleep(p)}
async function gap(p,index=0){return p.locator('.amx-ucolrow').evaluate((row,index)=>{const cells=row.querySelectorAll(':scope > .amx-ucolcell'),a=cells[index].getBoundingClientRect(),b=cells[index+1].getBoundingClientRect(),r=row.getBoundingClientRect();return{x:(a.right+b.left)/2,y:r.top+Math.min(80,r.height/2),height:r.height}},index)}
async function start(p,index=0){const r=await gap(p,index);await p.mouse.move(r.x,r.y);await sleep(p);await p.mouse.down();return r}
async function menu(p){const box=await p.locator('.amx-ucolcell p').first().boundingBox();await p.mouse.move(box.x+12,box.y+8);await sleep(p);await p.locator('.unified-gutter .drag-handle').click();await p.locator('[data-act="columnWidth"]').click();await p.locator('.amx-column-width input').waitFor();await sleep(p)}
async function main(){
 const browser=await chromium.launch({executablePath:findChromium(),headless:true})
 try{
  const p=await browser.newPage({locale:'zh-CN',viewport:{width:1200,height:850}})
  p.setDefaultTimeout(15000);p.on('pageerror',e=>errors.push(e.message))
  await p.goto(origin+'?upage&upane&useed='+encodeURIComponent(seed()))
  await p.locator('.amx-ucolrow').waitFor({timeout:120000});await sleep(p)
  await p.mouse.move(10,10);ok('no persistent boundary',await p.locator('.amx-column-boundary[data-visible]').count()===0)
  let r=await gap(p);await p.mouse.move(r.x,r.y);await sleep(p)
  const line=await p.locator('.amx-column-boundary').boundingBox()
  ok('hover shows full row-height 1px line',Math.abs(line.height-r.height)<2&&Math.abs(line.width-1)<.2)
  ok('hover exposes resize hint',await p.locator('.amx-column-boundary[data-visible]').textContent()==='左右拖动调列宽')
  await p.screenshot({path:path.join(out,'hover-light.png')})
  await p.locator('.amx-ucolcell p').first().hover();await sleep(p)
  ok('content hover hides seam feedback',await p.locator('.amx-column-boundary[data-visible]').count()===0)
  r=await start(p);await p.mouse.move(r.x+65,r.y,{steps:8})
  ok('drag previews without document transaction',near(await widths(p),[1,1])&&!near(await grow(p),[1,1]))
  ok('drag displays ratio',/\d+ : \d+/.test(await p.locator('.amx-column-boundary').textContent()))
  await p.mouse.up();await sleep(p)
  const savedWidths=await widths(p)
  ok('release commits only pair sum',savedWidths[0]>1&&Math.abs(savedWidths[0]+savedWidths[1]-2)<.0001)
  ok('release clears feedback',await p.locator('.amx-column-boundary[data-visible]').count()===0)
  await p.waitForTimeout(1200)
  const saved=await p.evaluate(()=>window.__upage.writes.at(-1).text)
  await p.evaluate(md=>window.__upage.switchFile('Reopened.md',md),saved);await sleep(p)
  ok('saved column widths survive reopen',near(await widths(p),savedWidths))
  await load(p)
  r=await start(p);await p.mouse.move(r.x+65,r.y);await p.keyboard.press('Escape');await p.mouse.up()
  ok('Escape restores both model and preview',near(await widths(p),[1,1])&&near(await grow(p),[1,1]))
  r=await start(p);await p.mouse.move(r.x+60,r.y)
  await p.evaluate(()=>window.dispatchEvent(new PointerEvent('pointercancel',{pointerId:1})));await p.mouse.up()
  ok('pointercancel restores preview',near(await widths(p),[1,1])&&near(await grow(p),[1,1]))
  r=await start(p);await p.mouse.move(r.x+65,r.y);await p.mouse.up()
  await p.evaluate(()=>window.__upage.probe.view().focus());await p.keyboard.press('Meta+z');await sleep(p)
  ok('one Undo restores original widths',near(await widths(p),[1,1]))
  await load(p,3);r=await start(p,1);await p.mouse.move(r.x+200,r.y);await p.mouse.up();await sleep(p)
  let w=await widths(p)
  ok('three-column resize leaves other column untouched and clamps pair',w[0]===1&&Math.abs(w[1]-1.7)<.001&&Math.abs(w[2]-.3)<.001)
  await load(p,2,true);r=await start(p);await p.mouse.move(r.x+50,r.y);await p.mouse.up();await sleep(p)
  ok('resizing preserves intentionally empty columns',(await widths(p)).length===2)
  await load(p);await menu(p);await p.keyboard.press('ArrowRight')
  ok('menu keyboard previews five percent',near(await widths(p),[1,1])&&near(await grow(p),[1.1,.9]))
  await p.keyboard.press('Escape');await sleep(p)
  ok('menu Escape cancels and restores editor focus',near(await grow(p),[1,1])&&await p.locator('.ProseMirror').evaluate(e=>e.contains(document.activeElement)))
  await menu(p);await p.keyboard.press('ArrowRight');await p.getByRole('button',{name:'取消',exact:true}).focus();await p.keyboard.press('Enter');await sleep(p)
  ok('Enter on Cancel does not commit a preview',near(await widths(p),[1,1])&&near(await grow(p),[1,1]))
  await menu(p);await p.keyboard.press('ArrowRight');await p.getByRole('button',{name:'均分',exact:true}).focus();await p.keyboard.press('Enter');await sleep(p)
  ok('Enter on Equal previews without closing dialog',await p.locator('.amx-column-width').count()===1&&near(await grow(p),[1,1]))
  await p.keyboard.press('Escape')
  await menu(p);await p.keyboard.press('ArrowLeft');await p.keyboard.press('Enter');await sleep(p)
  ok('menu Enter commits the chosen ratio',near(await widths(p),[.9,1.1]))
  await menu(p);await p.keyboard.press('ArrowRight');await p.mouse.click(10,10);await sleep(p)
  ok('outside dismissal cancels menu preview',near(await grow(p),[.9,1.1]))
  await load(p);r=await start(p);await p.mouse.move(r.x+55,r.y)
  await p.evaluate(()=>{const v=window.__upage.probe.view();v.dispatch(v.state.tr.insertText('Concurrent ',v.state.doc.firstChild.nodeSize+3))})
  await p.mouse.up();await sleep(p)
  ok('concurrent row edit cancels stale resize',near(await widths(p),[1,1])&&near(await grow(p),[1,1])&&(await p.locator('.ProseMirror').textContent()).includes('Concurrent'))
  await p.evaluate(()=>window.__upage.probe.view().setProps({editable:()=>false}));r=await start(p);await p.mouse.move(r.x+55,r.y);await p.mouse.up()
  ok('read-only notes cannot resize',near(await widths(p),[1,1])&&await p.locator('.amx-column-boundary[data-visible]').count()===0)
  await p.evaluate(()=>window.__upage.probe.view().setProps({editable:()=>true}));await load(p)
  for(const [mode,skin] of [['dark','classic'],['light','sage']]){
   await p.evaluate(async({mode,skin})=>(await import('/src/theme/loader.ts')).applyTheme('genesis',skin,skin,mode),{mode,skin})
   r=await gap(p);await p.mouse.move(r.x,r.y);await sleep(p)
   ok('boundary is colored in '+mode+' '+skin,await p.locator('.amx-column-boundary').evaluate(e=>getComputedStyle(e).backgroundColor!=='rgba(0, 0, 0, 0)'))
   await p.screenshot({path:path.join(out,`hover-${mode}-${skin}.png`)})
  }
  await p.evaluate(()=>document.documentElement.style.zoom='1.1');r=await gap(p);await p.mouse.move(r.x,r.y);await sleep(p)
  const zoomLine=await p.locator('.amx-column-boundary').boundingBox()
  ok('110 percent zoom keeps boundary in seam',Math.abs(zoomLine.x-r.x)<2&&Math.abs(zoomLine.height-r.height)<2)
  await p.screenshot({path:path.join(out,'hover-110.png')})
  await p.emulateMedia({reducedMotion:'reduce'})
  ok('reduced motion removes fade',await p.locator('.amx-column-boundary').evaluate(e=>getComputedStyle(e).transitionDuration)==='0s')
  await p.close()
  const touch=await browser.newContext({locale:'en-GB',viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const phone=await touch.newPage();phone.setDefaultTimeout(15000);phone.on('pageerror',e=>errors.push(e.message))
  await phone.goto(origin+'?upage&upane&useed='+encodeURIComponent(seed()));await phone.locator('.amx-ucolrow').waitFor({timeout:120000});await sleep(phone)
  r=await gap(phone);await phone.touchscreen.tap(r.x,r.y);await sleep(phone)
  ok('touching text gap does not start resize',near(await widths(phone),[1,1])&&await phone.locator('.amx-column-boundary[data-visible]').count()===0)
  await phone.locator('.amx-ucolcell p').first().tap();await sleep(phone)
  await phone.locator('.unified-gutter .drag-handle').tap();await phone.locator('[data-act="columnWidth"]').tap();await sleep(phone)
  const sheet=await phone.locator('.amx-column-width').boundingBox()
  ok('phone column menu is an English bottom sheet',sheet.x>=0&&sheet.x+sheet.width<=391&&sheet.y>400&&(await phone.locator('.amx-column-width').textContent()).includes('Adjust column widths'))
  ok('phone buttons have 44px touch targets',await phone.locator('.amx-column-width button').evaluateAll(es=>es.every(e=>e.getBoundingClientRect().height>=44)))
  const slider=await phone.locator('.amx-column-width input').boundingBox();await phone.touchscreen.tap(slider.x+slider.width*.7,slider.y+slider.height/2)
  await phone.getByRole('button',{name:'Done',exact:true}).tap();await sleep(phone)
  ok('touch slider applies chosen ratio',(await widths(phone))[0]>1)
  await phone.locator('.amx-ucolcell p').first().tap();await sleep(phone);await phone.locator('.unified-gutter .drag-handle').tap();await phone.locator('[data-act="columnWidth"]').tap();await sleep(phone)
  await phone.getByRole('button',{name:'Equal widths',exact:true}).tap();await phone.screenshot({path:path.join(out,'phone.png')});await phone.getByRole('button',{name:'Done',exact:true}).tap()
  ok('phone equal widths restores pair',near(await widths(phone),[1,1]))
  await touch.close();ok('no renderer errors',errors.length===0)
 }finally{fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({checks,errors},null,2));await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
