// Real preload/IPC + cross-process config lock; isolated data and stub backend. No external MCP commands run here.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const electron = require('./lib/launch-electron.cjs')
const { startStubEngine } = require('./lib/stub-engine.cjs')
const { skipOnboarding } = require('./lib/skip-onboarding.cjs')
const ROOT = path.resolve(__dirname, '..')
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'forsion-mcp-import-'))
const shots = process.env.MCP_SHOTS || path.join(home, 'shots')
fs.mkdirSync(shots, { recursive: true })
let passed = 0
const check = (name, ok) => { if (!ok) throw new Error(`FAIL ${name}`); passed++; console.log(`PASS ${name}`) }
async function main() {
  const stub = await startStubEngine({ sessions: [], messages: [], agents: [], engines: [] })
  const userdata = path.join(home, 'userdata')
  for (const dir of [userdata, `${userdata}-dev`]) { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(path.join(dir, 'tangu-desktop-config.json'), JSON.stringify({ mode: 'external', backendUrl: stub.url, token: 'e2e' })) }
  const original = { command: 'node', args: ['script.js', '/a path/with spaces'], env: { KEY: ' token with spaces ' }, headers: { Authorization: 'SECRET_HEADER' }, cwd: '/a path', timeoutMs: 4000, enabled: false }
  fs.writeFileSync(path.join(home, 'config.json'), JSON.stringify({ keep: 73, mcp: { mcpServers: { existing: original, minimal: { command: 'demo', enabled: false }, untouched: { url: 'https://keep.example/mcp', enabled: false } } } }))
  const app = await electron.launch({ args: [`--user-data-dir=${userdata}`, '--lang=zh-CN', ROOT], cwd: ROOT, env: { ...process.env, TANGU_HOME: home, TANGU_BACKEND_URL: stub.url, TANGU_HARNESS_QUIET: '1' } })
  try {
    const main = await app.firstWindow()
    await main.waitForSelector('#root', { timeout: 40000 })
    check('leave onboarding', await skipOnboarding(main))
    await main.evaluate(() => window.tangu.openFloatingPanel({ id: 'settings', title: 'Settings', builtin: 'settings', params: { tab: 'mcp', n: Date.now() } }))
    let win
    for (let i = 0; i < 150; i++) { win = app.windows().filter(w => !w.isClosed() && w.url().includes('window=floating')).pop(); if (win && await win.locator('.settings-sub--mcp').count()) break; await new Promise(r => setTimeout(r, 100)) }
    await win.locator('.settings-sub--mcp').waitFor()
    await app.evaluate(({ BrowserWindow }) => { for (const w of BrowserWindow.getAllWindows()) if (w.webContents.getURL().includes('window=floating')) w.setContentSize(1120, 820) })
    await win.evaluate(() => { document.body.style.zoom = '1.1'; document.documentElement.style.setProperty('--uiz', '1.1') })
    const read = () => win.evaluate(() => window.tangu.readMcpConfig())
    const dialog = () => win.getByRole('dialog', { name: /粘贴 JSON|Paste JSON/ })
    const button = () => win.getByRole('button', { name: /^(粘贴 JSON|Paste JSON)$/ })
    const open = async () => { await button().click(); await dialog().waitFor() }
    const fill = value => win.locator('#mcp-import-json').fill(typeof value === 'string' ? value : JSON.stringify(value, null, 2))
    const inspect = () => dialog().getByRole('button', { name: /检查配置|Check configuration/ }).click()
    const save = () => dialog().getByRole('button', { name: /添加并连接|Add and connect/ }).click()
    const shot = async name => { await win.waitForTimeout(180); await win.screenshot({ path: path.join(shots, `${name}.png`) }) }
    await open()
    check('textarea gets focus', await win.locator('#mcp-import-json').evaluate(e => e === document.activeElement))
    const before = JSON.stringify(await read())
    await fill('{ broken'); await inspect()
    check('invalid JSON shown; no write', (await dialog().getByRole('alert').innerText()).includes('JSON') && JSON.stringify(await read()) === before)
    const imported = { command: 'npx', args: ['-y', 'demo', '/a path/with spaces'], headers: { Authorization: 'SECRET_IMPORT' }, env: { TOKEN: 'SECRET_ENV' }, timeoutMs: 2345, cwd: '/a path', enabled: false }
    await fill({ mcpServers: { existing: imported, added: imported } }); await inspect()
    await dialog().getByText('added', { exact: true }).waitFor()
    check('preview does not expose credential values', !(await dialog().innerText()).includes('SECRET'))
    check('duplicate defaults to skip', !(await dialog().getByRole('checkbox').isChecked()))
    await dialog().getByRole('checkbox').check()
    await win.evaluate(async () => { const c = await window.tangu.readMcpConfig(); await window.tangu.writeMcpConfig({ base: c.mcpServers, mcpServers: { ...c.mcpServers, existing: { ...c.mcpServers.existing, timeoutMs: 9999 } } }) })
    await save(); await dialog().getByRole('alert').waitFor()
    check('concurrent replacement rejected, whole import unchanged', !(await read()).mcpServers.added && (await read()).mcpServers.existing.timeoutMs === 9999)
    await dialog().getByRole('button', { name: '返回编辑' }).click(); await inspect(); await dialog().getByRole('checkbox').check()
    await shot('B-preview-light')
    await save(); await dialog().waitFor({ state: 'hidden' })
    let configs = (await read()).mcpServers
    check('explicit replacement and exact arrays/headers/env/cwd/timeout persist', JSON.stringify(configs.existing) === JSON.stringify(imported) && JSON.stringify(configs.added) === JSON.stringify(imported))
    check('unrelated server preserved', configs.untouched.url === 'https://keep.example/mcp')
    await shot('B-saved-light')
    // Real manual edit/save preserves every field absent from the old manual form.
    const minimal = win.locator('.file-row').filter({ has: win.getByText('minimal', { exact: true }) })
    await minimal.getByTitle('编辑', { exact: true }).click()
    await win.locator('.settings-sub--mcp').getByRole('button', { name: '保存', exact: true }).click()
    await win.locator('.settings-sub--mcp').getByRole('button', { name: '保存', exact: true }).waitFor({ state: 'hidden' })
    check('command-only configuration remains editable', (await read()).mcpServers.minimal.command === 'demo')
    const row = win.locator('.file-row').filter({ has: win.getByText('existing', { exact: true }) })
    await row.getByTitle('编辑', { exact: true }).click()
    await win.locator('.settings-sub--mcp').getByRole('button', { name: '保存', exact: true }).click()
    await win.locator('.settings-sub--mcp').getByRole('button', { name: '保存', exact: true }).waitFor({ state: 'hidden' })
    check('manual round trip preserves hidden fields and spaced arguments', JSON.stringify((await read()).mcpServers.existing) === JSON.stringify(imported))
    await open(); await fill({ existing: { command: 'different', enabled: false }, second: { url: 'https://new.example/mcp', enabled: false } }); await inspect(); await save(); await dialog().waitFor({ state: 'hidden' })
    configs = (await read()).mcpServers
    check('named map merges; unselected duplicate remains untouched', JSON.stringify(configs.existing) === JSON.stringify(imported) && configs.second.url === 'https://new.example/mcp')
    await open(); await fill({ url: 'https://single.example/SECRET_PATH/mcp?token=SECRET_QUERY', headers: { Authorization: 'SECRET_SINGLE' }, enabled: false }); await inspect()
    await win.locator('#mcp-import-name').waitFor(); await win.locator('#mcp-import-name').fill('single'); await inspect(); await dialog().getByText('single', { exact: true }).waitFor(); check('URL path/query credentials hidden in preview', !(await dialog().innerText()).includes('SECRET')); await save(); await dialog().waitFor({ state: 'hidden' })
    check('single object requests name and saves', (await read()).mcpServers.single.headers.Authorization === 'SECRET_SINGLE')
    await open(); await fill({ draft: { url: 'https://draft.example/mcp', unknown: true } }); await inspect()
    check('unsupported field is visible', (await dialog().getByRole('alert').innerText()).includes('不支持'))
    await win.keyboard.press('Escape'); await dialog().waitFor({ state: 'hidden' })
    check('Escape restores entry focus', await button().evaluate(e => e === document.activeElement))
    await open(); check('cancelled draft retained', (await win.locator('#mcp-import-json').inputValue()).includes('draft.example'))
    await fill({ mcpServers: { themed: { url: 'https://example.com/mcp', enabled: false } } })
    await shot('B-paste-light')
    await win.evaluate(() => { document.documentElement.classList.add('dark'); document.documentElement.dataset.mode = 'dark' })
    await shot('B-paste-dark')
    await win.evaluate(() => { const r = document.documentElement; r.classList.remove('dark'); r.dataset.mode = 'light'; r.dataset.skin = 'sage'; r.dataset.bg = 'sage' })
    await shot('B-paste-sage')
    await app.evaluate(({ BrowserWindow }) => { for (const w of BrowserWindow.getAllWindows()) if (w.webContents.getURL().includes('window=floating')) w.setContentSize(700, 900) })
    await shot('B-paste-narrow')
    const bounds = await dialog().boundingBox()
    check('narrow dialog fits viewport', bounds.x >= 0 && bounds.x + bounds.width <= 701 && bounds.y >= 0 && bounds.y + bounds.height <= 901)
    await win.keyboard.press('Escape')
    await win.evaluate(() => localStorage.setItem('tangu_locale', 'en'))
    await win.reload({ waitUntil: 'domcontentloaded' }); await win.locator('.settings-sub--mcp').waitFor(); await open()
    check('English dialog uses translated labels', await dialog().getByRole('button', { name: 'Check configuration' }).count() === 1)
    await shot('B-paste-en')
    const disk = JSON.parse(fs.readFileSync(path.join(home, 'config.json'), 'utf8'))
    check('other config sections preserved', disk.keep === 73)
    fs.writeFileSync(path.join(shots, 'report.json'), JSON.stringify({ passed, home, shots }, null, 2))
    console.log(`PASS ${passed} checks; screenshots: ${shots}`)
  } finally { await app.close(); stub.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
