package com.forsion.tangu.localengine;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import org.json.JSONArray;
import org.json.JSONObject;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.StandardCopyOption;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.Signature;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The engine package check the phone runs before anything in a download executes. The fixture
 * (src/test/resources/local-engine-fixture, regenerated by mobile/scripts/local-engine/make-test-fixture.mjs) is signed by
 * the Node producer: passing it proves the two halves agree byte for byte. Everything else is refused for one reason each.
 */
public class EngineSignatureTest {
    @Rule public TemporaryFolder tmp = new TemporaryFolder();

    private static final String PKG = "@forsion/tangu-engine-android-arm64";
    private static final File FIXTURE = new File("src/test/resources/local-engine-fixture");
    private File tree;
    private List<byte[]> keys;

    @Before public void copyFixture() throws Exception {
        tree = tmp.newFolder("package");
        copy(new File(FIXTURE, "package"), tree);
        keys = Collections.singletonList(EngineSignature.unhex(read(new File(FIXTURE, "test-key.hex")).trim()));
    }

    private EngineSignature.Result verify() throws Exception {
        return EngineSignature.verify(tree, keys, PKG, "2.14.10", 1, "2.14.10", null, null);
    }

    private void refused(String why) throws Exception {
        try {
            verify();
            fail("accepted: " + why);
        } catch (EngineSignature.Refused expected) {
            // fine
        }
    }

    @Test public void theNodeProducersFixtureVerifies() throws Exception {
        EngineSignature.Result r = verify();
        assertEquals("2.14.10", r.version);
        assertEquals(1, r.line);
        assertEquals(8, r.files);
    }

    @Test public void anotherKeyIsRefused() throws Exception {
        keys = Collections.singletonList(EngineSignature.unhex(EngineSignature.PRODUCTION_KEY_HEX));
        refused("signed with the fixture key, checked against the production key");
    }

    @Test public void tamperedFilesAreRefused() throws Exception {
        File f = new File(tree, "node_modules/dep/index.js");
        Files.write(f.toPath(), "module.exports = 2\n".getBytes(StandardCharsets.UTF_8)); // same size, other bytes
        refused("a dependency changed after signing");
    }

    @Test public void extraMissingAndLinkedFilesAreRefused() throws Exception {
        Files.write(new File(tree, "node_modules/dep/extra.js").toPath(), new byte[]{1});
        refused("an extra file");
        new File(tree, "node_modules/dep/extra.js").delete();
        verify();
        new File(tree, "skills/a/SKILL.md").delete();
        refused("a missing file");
        Files.copy(new File(FIXTURE, "package/skills/a/SKILL.md").toPath(), new File(tree, "skills/a/SKILL.md").toPath());
        verify();
        File dep = new File(tree, "node_modules/dep/index.js");
        dep.delete();
        Files.createSymbolicLink(dep.toPath(), new File(FIXTURE, "package/node_modules/dep/index.js").getAbsoluteFile().toPath());
        refused("a link where a file was signed");
    }

    @Test public void theSignedTableItselfIsCovered() throws Exception {
        File s = new File(tree, EngineSignature.SIGNED_FILE);
        String t = read(s).replace("\"line\":1", "\"line\":1 ");
        Files.write(s.toPath(), t.getBytes(StandardCharsets.UTF_8));
        refused("one byte of whitespace added to the signed table");
    }

    @Test public void askedForIdentity() throws Exception {
        try { EngineSignature.verify(tree, keys, PKG + "-x", "2.14.10", 1, null, null, null); fail("name"); } catch (EngineSignature.Refused ok) {}
        try { EngineSignature.verify(tree, keys, PKG, "2.14.11", 1, null, null, null); fail("a stale mirror's version"); } catch (EngineSignature.Refused ok) {}
        try { EngineSignature.verify(tree, keys, PKG, "2.14.10", 2, null, null, null); fail("another line"); } catch (EngineSignature.Refused ok) {}
        try { EngineSignature.verify(tree, keys, PKG, "2.14.10", 1, "2.14.11", null, null); fail("below the APK's minimum"); } catch (EngineSignature.Refused ok) {}
        EngineSignature.verify(tree, keys, PKG, null, 1, "1.0.0", null, null); // re-verifying what is on disk
    }

    /** A desktop SIGNATURE is a JSON table signed without the context line under the same key: it must not pass here. */
    @Test public void aDesktopStyleSignatureNeverPasses() throws Exception {
        KeyPair kp = KeyPairGenerator.getInstance("Ed25519").generateKeyPair();
        keys = Collections.singletonList(Ed25519.rawFromSpki(kp.getPublic().getEncoded()));
        byte[] table = Files.readAllBytes(new File(tree, EngineSignature.SIGNED_FILE).toPath());
        writeSig(kp, table); // no context line
        refused("signature over the table without the context line");
        byte[] ctx = EngineSignature.CONTEXT.getBytes(StandardCharsets.UTF_8);
        byte[] msg = new byte[ctx.length + table.length];
        System.arraycopy(ctx, 0, msg, 0, ctx.length);
        System.arraycopy(table, 0, msg, ctx.length, table.length);
        writeSig(kp, msg);
        verify(); // the same bytes with the context: fine
    }

    @Test public void tooManyFilesIsRefusedBeforeTheTreeIsRead() throws Exception {
        KeyPair kp = KeyPairGenerator.getInstance("Ed25519").generateKeyPair();
        keys = Collections.singletonList(Ed25519.rawFromSpki(kp.getPublic().getEncoded()));
        JSONObject t = new JSONObject(read(new File(tree, EngineSignature.SIGNED_FILE)));
        JSONObject files = t.getJSONObject("files");
        for (int i = 0; i <= EngineSignature.MAX_FILES; i++) files.put("pad/" + i, new JSONArray().put("0".repeat(64)).put(0));
        signTable(kp, t);
        refused("more than MAX_FILES entries");
    }

    @Test public void unsafePathsAndAWrongFingerprintAreRefused() throws Exception {
        KeyPair kp = KeyPairGenerator.getInstance("Ed25519").generateKeyPair();
        keys = Collections.singletonList(Ed25519.rawFromSpki(kp.getPublic().getEncoded()));
        JSONObject t = new JSONObject(read(new File(tree, EngineSignature.SIGNED_FILE)));
        t.getJSONObject("files").put("../escape.js", new JSONArray().put("0".repeat(64)).put(0));
        signTable(kp, t);
        refused("a path outside the tree");
        t = new JSONObject(read(new File(FIXTURE, "package/" + EngineSignature.SIGNED_FILE)));
        t.put("schemaFingerprint", "0".repeat(64));
        signTable(kp, t);
        refused("a fingerprint that does not recompute");
        for (String p : new String[]{"a//b", "/a", "a/", "a/./b", "a\\b", EngineSignature.SIG_FILE}) assertTrue(p, !EngineSignature.safePath(p));
    }

    /** The key in the APK is the engine signing key the desktop pins (tangu-agent/src/boot/signingKey.ts). */
    @Test public void productionKeyIsTheEngineSigningKey() throws Exception {
        String ts = read(new File("../../../tangu-agent/src/boot/signingKey.ts"));
        Matcher m = Pattern.compile("-----BEGIN PUBLIC KEY-----\\s*([A-Za-z0-9+/=]+)\\s*-----END PUBLIC KEY-----").matcher(ts);
        assertTrue(m.find());
        byte[] raw = Ed25519.rawFromSpki(java.util.Base64.getDecoder().decode(m.group(1)));
        assertEquals(EngineSignature.hex(raw), EngineSignature.PRODUCTION_KEY_HEX);
    }

    /** The Java consumer and the Node producer (android-engine-format.mjs) share their constants. */
    @Test public void constantsMatchTheProducer() throws Exception {
        String js = read(new File("../../scripts/local-engine/android-engine-format.mjs"));
        assertEquals("'" + EngineSignature.CONTEXT.replace("\n", "\\n") + "'", group(js, "export const CONTEXT = ('[^']*')"));
        assertEquals("'" + EngineSignature.SIGNED_FILE + "'", group(js, "export const SIGNED_FILE = ('[^']*')"));
        assertEquals("'" + EngineSignature.SIG_FILE + "'", group(js, "export const SIG_FILE = ('[^']*')"));
        assertEquals(String.valueOf(EngineSignature.MAX_FILES), group(js, "export const MAX_FILES = (\\d+)"));
        assertEquals(EngineSignature.MAX_BYTES, 400L << 20);
        assertTrue(js.contains("export const MAX_BYTES = 400 * 1024 * 1024"));
        // the README's schema file list is the producer's
        String readme = read(new File("../local-engine/README.md"));
        Matcher m = Pattern.compile("'(dist/[^']+\\.js)'").matcher(group(js, "export const SCHEMA_FILES = \\[([^\\]]*)\\]"));
        List<String> schema = new ArrayList<>();
        while (m.find()) schema.add(m.group(1));
        assertEquals(4, schema.size());
        for (String s : schema) assertTrue(s, readme.contains("`" + s + "`"));
    }

    // ---------- helpers ----------

    private void signTable(KeyPair kp, JSONObject t) throws Exception {
        byte[] bytes = t.toString().getBytes(StandardCharsets.UTF_8);
        Files.write(new File(tree, EngineSignature.SIGNED_FILE).toPath(), bytes);
        byte[] ctx = EngineSignature.CONTEXT.getBytes(StandardCharsets.UTF_8);
        byte[] msg = new byte[ctx.length + bytes.length];
        System.arraycopy(ctx, 0, msg, 0, ctx.length);
        System.arraycopy(bytes, 0, msg, ctx.length, bytes.length);
        writeSig(kp, msg);
    }

    private void writeSig(KeyPair kp, byte[] msg) throws Exception {
        Signature s = Signature.getInstance("Ed25519");
        s.initSign(kp.getPrivate());
        s.update(msg);
        Files.write(new File(tree, EngineSignature.SIG_FILE).toPath(), (java.util.Base64.getEncoder().encodeToString(s.sign()) + "\n").getBytes(StandardCharsets.US_ASCII));
    }

    private static String group(String s, String re) {
        Matcher m = Pattern.compile(re).matcher(s);
        assertTrue(re, m.find());
        return m.group(1);
    }

    private static String read(File f) throws Exception { return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8); }

    private static void copy(File from, File to) throws Exception {
        if (from.isDirectory()) {
            to.mkdirs();
            for (String k : from.list()) copy(new File(from, k), new File(to, k));
        } else {
            Files.copy(from.toPath(), to.toPath(), StandardCopyOption.REPLACE_EXISTING);
        }
    }
}
