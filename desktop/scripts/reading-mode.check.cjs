/** Isolated browser check of the production UnifiedPage, reading surface and renderer registry. */
const fs = require('fs')
const os = require('os')
const path = require('path')
const assert = require('assert/strict')
const { chromium } = require('playwright-core')
const base = process.env.HARNESS_URL || 'http://127.0.0.1:5277/harness.html'
function executable() {
  if (process.env.CHROMIUM_EXE) return process.env.CHROMIUM_EXE
  const root = path.join(os.homedir(), 'Library/Caches/ms-playwright')
  for (const d of fs.readdirSync(root).filter((x) => x.startsWith('chromium-')).sort().reverse()) {
    for (const name of ['Google Chrome for Testing', 'Chromium']) {
      const file = path.join(root, d, 'chrome-mac-arm64', `${name}.app/Contents/MacOS/${name}`)
      if (fs.existsSync(file)) return file
    }
  }
  throw new Error('Set CHROMIUM_EXE to a Chromium executable')
}
const seed = '# Reading mode\n\n<u>physics · path · geometry</u> and $p = mv$.\n\n' + Array.from({ length: 45 }, (_, i) => `## Section ${i + 1}\n\nParagraph ${i + 1}: The editor keeps its document, selection and undo history while a separate module renders the reading surface.`).join('\n\n')
async function main() {
  const browser = await chromium.launch({ executablePath: executable(), headless: true })
  const page = await browser.newPage({ viewport: { width: 1200, height: 850 }, locale: 'en-GB' })
  const errors = []
  page.on('pageerror', (e) => { errors.push(e.message); console.error('PAGE ERROR', e.message) })
  try {
    await page.goto(`${base}?upage&upane&utoc&useed=${encodeURIComponent(seed)}`)
    await page.waitForFunction(() => window.__upage?.probe?.view?.())
    await page.evaluate(() => { window.__savedView = window.__upage.probe.view() })
    const editor = page.locator('.unified-body .ProseMirror').first()
    await editor.locator('p').first().click()
    await page.keyboard.type(' LAST-INPUT')
    // First check the immediate keystroke handoff, then measure long-document position independently.
    await page.locator('[data-reading-toggle]').click()
    await page.locator('[data-reading-surface] .ProseMirror').waitFor()
    assert.match(await page.evaluate(() => window.__upage.vault.get('Unified.md')), /LAST-INPUT/)
    await page.evaluate(() => window.__upage.probe.setReading(false))
    await page.locator('[data-reading-surface]').waitFor({state:'detached'})
    await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await page.evaluate(() => { document.querySelector('.amx-pane').scrollTop = 720 })
    const top = await page.locator('.amx-pane').evaluate((el) => el.scrollTop)
    const beforeAnchor = await page.evaluate(() => [...document.querySelectorAll('.unified-body .ProseMirror h2')].map((el) => ({ text: el.textContent, top: el.getBoundingClientRect().top })).find((el) => el.top >= 0))
    await page.locator('[data-reading-toggle]').click()
    await page.locator('[data-reading-surface] .ProseMirror').waitFor()
    assert.equal(await page.evaluate(() => window.__savedView === window.__upage.probe.view()), true, 'The editor must not remount')
    assert.match(await page.evaluate(() => window.__upage.vault.get('Unified.md')), /LAST-INPUT/, 'The latest keystroke must be saved')
    assert.equal(await page.locator('[data-reading-surface] [contenteditable]').count(), 0)
    assert.equal(await page.locator('[data-reading-surface] u').evaluate((el) => getComputedStyle(el).textDecorationSkipInk), 'none')
    const readTop = await page.locator('.amx-pane').evaluate((el) => el.scrollTop)
    const afterAnchor = await page.evaluate(() => [...document.querySelectorAll('[data-reading-surface] h2')].map((el) => ({ text: el.textContent, top: el.getBoundingClientRect().top })).find((el) => el.top >= 0))
    const captured = await page.evaluate(() => window.__upage.probe.readingPosition())
    assert.ok(beforeAnchor?.text === afterAnchor?.text && Math.abs(beforeAnchor.top - afterAnchor.top) < 100, `Reading position changed: ${top} -> ${readTop}; ${JSON.stringify(beforeAnchor)} -> ${JSON.stringify(afterAnchor)}; captured=${JSON.stringify(captured)}`)
    await page.screenshot({ path: '/tmp/forsion-reading-light.png' })
    console.log('PASS live input saved, editor retained, underline continuous, position retained')
    await page.evaluate(async () => {
      const { registerNoteRenderer } = await import('/src/amadeus/plugins/noteRenderers.ts')
      window.__badReadingOff = registerNoteRenderer('test-reader', { id: 'reader', apiVersion: 1, mount() { throw new Error('expected bad update') } })
    })
    await page.getByRole('status').filter({ hasText: /上一版本|previous version/ }).waitFor()
    assert.match(await page.locator('[data-reading-surface]').innerText(), /Paragraph 1/)
    await page.evaluate(async () => {
      const { registerNoteRenderer } = await import('/src/amadeus/plugins/noteRenderers.ts')
      window.__goodReadingOff = registerNoteRenderer('test-reader', { id: 'reader', apiVersion: 1, mount(el, snapshot) { el.innerHTML = '<div data-module-version="2">Updated renderer</div>' + snapshot.html; return () => {} } })
    })
    await page.locator('[data-module-version="2"]').waitFor()
    assert.equal(await page.evaluate(() => window.__savedView === window.__upage.probe.view()), true)
    await page.evaluate(() => { window.__badReadingOff(); window.__goodReadingOff() })
    await page.locator('[data-module-version="2"]').waitFor({ state: 'detached' })
    console.log('PASS failed renderer keeps previous surface; successful hot update and disable use host lifecycle')
    await page.evaluate(() => window.__upage.probe.setReading(false))
    await page.locator('[data-reading-surface]').waitFor({ state: 'detached' })
    assert.equal(await page.evaluate(() => window.__savedView === window.__upage.probe.view()), true)
    await editor.locator('p').first().click()
    await page.keyboard.press('Meta+z')
    await page.waitForFunction(() => !window.__upage.probe.view().state.doc.textContent.includes('LAST-INPUT'))
    console.log('PASS original undo history survives reading and renderer hot updates')
    await page.keyboard.type(' SAVE-FAILURE-DRAFT')
    await page.evaluate(() => { window.__upage.failWrites = 100 })
    await page.evaluate(() => window.__upage.probe.setReading(true))
    assert.equal(await page.locator('[data-reading-surface]').count(), 0)
    assert.match(await editor.innerText(), /SAVE-FAILURE-DRAFT/)
    await page.evaluate(() => { window.__upage.failWrites = 0 })
    await page.evaluate(() => window.__upage.probe.setReading(true))
    await page.locator('[data-reading-surface]').waitFor()
    assert.match(await page.evaluate(() => window.__upage.vault.get('Unified.md')), /SAVE-FAILURE-DRAFT/)
    console.log('PASS save failure keeps editable draft; retry succeeds')
    const interactions = '# Reading interactions\n\n<u>physics · path · geometry</u> and $p = mv$.\n\n[[Linked]] · [Web](https://example.test/page) · [Report](report.pdf) · [Jump](#section-25)\n\n![Preview](https://example.test/figure.svg)\n\n- [x] Complete\n- [ ] Pending\n\n' + seed.slice(seed.indexOf('## Section 1'))
    await page.route('https://example.test/figure.svg', (route) => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="100"><rect width="360" height="100" fill="#dfede5"/><path d="M24 20V78H336M30 68C90 68 75 30 140 42S225 72 245 32S305 20 330 35" fill="none" stroke="#567a65" stroke-width="2"/></svg>' }))
    await page.goto(`${base}?upage&upane&utoc&useed=${encodeURIComponent(interactions)}`)
    await page.waitForFunction(() => window.__upage?.probe?.view?.())
    await page.evaluate(() => {
      window.__readingLinks = []
      window.open = (href) => { window.__readingLinks.push(['web', href]); return null }
      window.amadeus.openAttachment = async (path, href) => { window.__readingLinks.push(['attachment', path, href]) }
      window.__upage.pageStore.setState({ openWikiLink: async (href, path) => { window.__readingLinks.push(['wiki', href, path]) } })
    })
    await page.locator('[data-reading-toggle]').click()
    await page.locator('[data-reading-surface] .ProseMirror').waitFor()
    await page.locator('[data-reading-surface] [data-wiki]').first().click()
    await page.locator('[data-reading-surface] a').filter({ hasText: /^Web$/ }).click()
    await page.locator('[data-reading-surface] a').filter({ hasText: /^Report$/ }).click()
    assert.deepEqual(await page.evaluate(() => window.__readingLinks), [['wiki', 'Linked', 'Unified.md'], ['web', 'https://example.test/page'], ['attachment', 'Unified.md', 'report.pdf']])
    await page.locator('[data-reading-surface] img').first().dblclick()
    await page.locator('.amx-lightbox').waitFor()
    await page.keyboard.press('Escape')
    await page.locator('.amx-lightbox').waitFor({ state: 'detached' })
    await page.locator('[data-reading-surface] a').filter({ hasText: /^Jump$/ }).click()
    await page.waitForFunction(() => Math.abs([...document.querySelectorAll('[data-reading-surface] h2')].find((el) => el.textContent === 'Section 25').getBoundingClientRect().top - document.querySelector('.amx-toolbar').getBoundingClientRect().bottom - 12) < 3)
    await page.getByRole('button', { name: 'toc', exact: true }).click()
    await page.locator('.lcl-ftoc-item').filter({ hasText: /^Section 15$/ }).click()
    await page.waitForFunction(() => Math.abs([...document.querySelectorAll('[data-reading-surface] h2')].find((el) => el.textContent === 'Section 15').getBoundingClientRect().top - document.querySelector('.amx-toolbar').getBoundingClientRect().bottom - 12) < 3)
    await page.keyboard.press('Escape')
    await page.evaluate(() => { document.querySelector('.amx-pane').scrollTop = 0 })
    await page.mouse.move(1000, 60)
    await page.locator('[data-reading-toggle]').focus()
    await page.locator('.lcl-ftoc-panel').waitFor({ state: 'detached' })
    await page.screenshot({ path: '/tmp/forsion-reading-light.png' })
    console.log('PASS wiki, web, attachment, internal anchor, floating outline and image preview delegates')
    await page.goto(`${base}?upage&upane&udark&useed=${encodeURIComponent(interactions)}`)
    await page.waitForFunction(() => window.__upage?.probe?.view?.())
    await page.locator('[data-reading-toggle]').click()
    await page.locator('[data-reading-surface]').waitFor()
    await page.evaluate(() => document.fonts.ready)
    await page.waitForFunction(() => [...document.querySelectorAll('[data-reading-surface] img')].every((img) => img.complete && img.naturalWidth > 0))
    await page.screenshot({ path: '/tmp/forsion-reading-dark.png' })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: '/tmp/forsion-reading-narrow.png' })
    assert.ok(await page.evaluate(() => document.body.scrollWidth <= innerWidth), 'Narrow reader must not overflow horizontally')
    console.log('PASS light/dark/narrow reading screenshots')
    assert.deepEqual(errors, [], 'No page runtime errors')
  } catch (e) { await page.screenshot({ path: '/tmp/forsion-reading-failure.png' }); console.error((await page.locator('body').innerText()).slice(0, 800)); throw e }
  finally { await browser.close() }
}
main().catch((e) => { console.error(e); process.exitCode = 1 })
