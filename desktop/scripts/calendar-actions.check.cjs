/** Repeatable desktop + phone touch regression. Bridge/chrome stand-ins are explicit; disk is tested in calendar-ui. */
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const os = require('node:os')
const { chromium } = require('playwright-core')
const { findChromium } = require('./lib/find-chromium.cjs')
const OUT = process.env.CALENDAR_ACTIONS_OUT || path.join(os.tmpdir(), 'forsion-calendar-actions')
let count = 0
const check = (name, value) => { assert.ok(value, name); console.log(`PASS ${++count}: ${name}`) }
const key = (id) => `[data-key="Events.db::${id}"]`
const rows = (page) => page.evaluate(() => window.__calTest.db.getState().entries['Events.db'].data.rows)
async function align(page) {
  await page.evaluate(() => {
    const sc = document.querySelector('.amx-cal-tscroll'), day = window.__calTest.day
    const cell = document.querySelector(`.amx-cal-daycol2[data-date="${day}"]`)
    sc.scrollLeft = cell.offsetLeft
    sc.scrollTop = cell.offsetTop + 8.5 * 56
    sc.dispatchEvent(new Event('scroll'))
  })
  await page.waitForTimeout(150)
}
async function touchDrag(page, x, y, dx, dy) {
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let i = 1; i <= 10; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + dx * i / 10, y: y + dy * i / 10 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await cdp.detach()
  await page.waitForTimeout(200)
}
async function main() {
  fs.mkdirSync(OUT, { recursive: true })
  const { createServer } = await import('vite')
  const server = await createServer({ root: path.resolve('frontend'), server: { port: 5199, strictPort: true } })
  await server.listen()
  const browser = await chromium.launch({ executablePath: findChromium(), headless: true })
  const errors = []
  try {
    const desktop = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'zh-CN' })
    const page = await desktop.newPage()
    page.on('pageerror', (e) => errors.push(e.message))
    await page.goto('http://localhost:5199/calendar-actions.html')
    await page.locator(key('short')).waitFor()
    await align(page)
    await page.locator(key('short')).click({ position: { x: 20, y: 3 } })
    check('desktop edge tap opens a nonblocking card', await page.locator('.calendar .amx-cal-cardwrap').count() === 1)
    await page.keyboard.press('Control+d')
    await page.waitForTimeout(150)
    check('Ctrl+D clones selected event', (await rows(page)).length === 4)
    await page.keyboard.press('Control+z')
    check('Ctrl+Z removes clone', (await rows(page)).length === 3)
    await page.keyboard.press('Control+Shift+z')
    check('Ctrl+Shift+Z restores clone', (await rows(page)).length === 4)
    await page.locator(key('long')).click({ button: 'right' })
    await page.waitForTimeout(200)
    await page.screenshot({ path: path.join(OUT, 'desktop-context-observation.png') })
    check('right click selects the event and opens actions', await page.getByRole('menuitem', { name: '克隆', exact: true }).count() === 1)
    await page.screenshot({ path: path.join(OUT, 'desktop-menu.png') })
    await page.keyboard.press('Escape')
    await page.locator(key('long')).click()
    await page.getByRole('textbox', { name: '名称', exact: true }).fill('A title')
    await page.keyboard.press('Control+d')
    check('input shortcuts do not clone events', (await rows(page)).length === 4)
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.locator(key('long')).click()
    let r = await page.locator(key('long')).boundingBox()
    await page.mouse.move(r.x + r.width / 2, r.y + r.height / 2)
    await page.mouse.down(); await page.mouse.move(r.x + r.width / 2, r.y + r.height / 2 + 56, { steps: 10 }); await page.mouse.up()
    check('desktop selected body drag moves one hour and preserves duration', (await rows(page)).find((x) => x.id === 'long').cells.date.includes('T10:30/'))
    await page.keyboard.press('Control+z')
    await page.locator(key('long')).click()
    r = await page.locator(key('long')).boundingBox()
    await page.mouse.move(r.x + r.width / 2, r.y + r.height - 2); await page.mouse.down(); await page.mouse.move(r.x + r.width / 2, r.y + r.height + 26, { steps: 8 }); await page.mouse.up()
    check('desktop invisible bottom boundary resizes', (await rows(page)).find((x) => x.id === 'long').cells.date.endsWith('T11:30'))
    await page.screenshot({ path: path.join(OUT, 'desktop-resized.png') })
    await page.keyboard.press('Control+z')
    await page.locator(key('long')).click()
    await page.keyboard.press('Control+x')
    check('desktop cut only marks the original', (await rows(page)).length === 4 && await page.locator(`${key('long')}.cut`).count() === 1)
    const pasteSlot = await page.evaluate(() => {
      const day = new Date(`${window.__calTest.day}T00:00`); day.setDate(day.getDate()+1)
      const iso = `${day.getFullYear()}-${String(day.getMonth()+1).padStart(2,'0')}-${String(day.getDate()).padStart(2,'0')}`
      const cell = document.querySelector(`.amx-cal-daycol2[data-date="${iso}"]`), r = cell.getBoundingClientRect(), z = cell.currentCSSZoom || 1
      return { x: r.left + r.width/2, y: r.top + 13*56*z + 4 }
    })
    await page.mouse.click(pasteSlot.x, pasteSlot.y, { button: 'right' })
    await page.getByRole('menuitem', { name: '粘贴', exact: true }).click()
    check('context paste moves the cut row into target slot without cloning', (await rows(page)).length === 4 && (await rows(page)).find((x) => x.id === 'long').cells.date.includes('T13:00/'))
    await page.keyboard.press('Control+z')
    await page.locator(key('long')).click()
    const beforeCancel = (await rows(page)).find((x) => x.id === 'long').cells.date
    r = await page.locator(key('long')).boundingBox()
    await page.mouse.move(r.x + r.width/2, r.y + r.height/2); await page.mouse.down(); await page.mouse.move(r.x + r.width/2, r.y + r.height/2 + 28, { steps: 5 })
    await page.keyboard.press('Escape'); await page.mouse.up()
    check('Escape cancels drag without writes or leftover ghosts', (await rows(page)).find((x) => x.id === 'long').cells.date === beforeCancel && await page.locator('.drag-shadow, .dragging').count() === 0)
    await page.locator(key('long')).click()
    const copyBody = (await rows(page)).find((x) => x.id === 'long').body
    await page.keyboard.press('Control+c')
    await page.keyboard.press('Escape')
    await page.locator(key('long')).click()
    await page.keyboard.press('Delete')
    await page.keyboard.press('Control+v')
    await page.waitForTimeout(100)
    check('copied snapshot survives Escape and source deletion, then pastes its body', (await rows(page)).length === 4 && !(await rows(page)).some((x) => x.id === 'long') && (await rows(page)).some((x) => x.body === copyBody))
    await page.keyboard.press('Control+z'); await page.keyboard.press('Control+z')
    await desktop.close()

    const phone = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, locale: 'zh-CN' })
    const mobile = await phone.newPage()
    mobile.on('pageerror', (e) => errors.push(e.message))
    await mobile.goto('http://localhost:5199/calendar-actions.html?ui=mobile')
    await mobile.locator(key('short')).waitFor()
    await align(mobile)
    check('phone carrier has native touch input', await mobile.evaluate(() => navigator.maxTouchPoints > 0))
    r = await mobile.locator(key('short')).boundingBox()
    const beforeScroll = await mobile.locator('.amx-cal-tscroll').evaluate((el) => el.scrollTop)
    await touchDrag(mobile, r.x + r.width/2, r.y + r.height/2, 0, -75)
    check('swiping an unselected phone event scrolls without opening details', await mobile.locator('.amx-cal-drawer').count() === 0 && await mobile.locator('.amx-cal-tscroll').evaluate((el) => el.scrollTop) > beforeScroll)
    await align(mobile)
    r = await mobile.locator(key('short')).boundingBox()
    await mobile.touchscreen.tap(r.x + r.width / 2, r.y + 3)
    await mobile.locator('.amx-cal-drawer').waitFor()
    check('phone short-event edge tap opens drawer', await mobile.locator('.amx-cal-handle').count() === 2)
    check('drawer claims native chrome and hides dock', await mobile.evaluate(() => document.documentElement.dataset.dock === 'hidden'))
    const geometry = await mobile.locator('.amx-cal-drawer').boundingBox()
    check('drawer is flush to phone bottom', Math.abs(geometry.y + geometry.height - 852) < 2)
    await mobile.screenshot({ path: path.join(OUT, 'phone-details.png') })
    await mobile.evaluate(() => window.dispatchEvent(new CustomEvent('forsion:mobile-back', { cancelable: true, detail: { probe: true } })))
    check('predictive back probe has no side effect', await mobile.locator('.amx-cal-drawer').count() === 1)
    await mobile.getByRole('button', { name: '事件操作', exact: true }).tap()
    await mobile.getByRole('menuitem', { name: '删除', exact: true }).tap()
    check('phone can delete without a Delete key', !(await rows(mobile)).some((x) => x.id === 'short'))
    await mobile.keyboard.press('Control+z')
    check('phone deletion is undoable', (await rows(mobile)).some((x) => x.id === 'short'))
    await align(mobile)
    await mobile.locator(key('long')).tap()
    let handle = await mobile.locator('.amx-cal-handle.end').boundingBox()
    check('phone resize control has 44px touch target', handle.width >= 44 && handle.height >= 44)
    await touchDrag(mobile, handle.x + 22, handle.y + 22, 0, 28)
    check('phone bottom round control resizes event', (await rows(mobile)).find((x) => x.id === 'long').cells.date.endsWith('T11:30'))
    check('drag collapses drawer to live time summary', await mobile.locator('.amx-cal-drawer.collapsed').count() === 1)
    await mobile.screenshot({ path: path.join(OUT, 'phone-drag-summary.png') })
    const beforeTouchCancel = (await rows(mobile)).find((x) => x.id === 'long').cells.date
    handle = await mobile.locator('.amx-cal-handle.start').boundingBox()
    const cancelled = await mobile.context().newCDPSession(mobile)
    await cancelled.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: handle.x+22, y: handle.y+22 }] })
    await cancelled.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: handle.x+22, y: handle.y+50 }] })
    await cancelled.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
    await cancelled.detach()
    check('phone pointer cancellation restores event without writing', (await rows(mobile)).find((x) => x.id === 'long').cells.date === beforeTouchCancel)
    await mobile.getByRole('button', { name: '展开详情', exact: true }).first().tap()
    await mobile.getByRole('button', { name: '事件操作', exact: true }).tap()
    await mobile.getByRole('menuitem', { name: '复制', exact: true }).tap()
    await mobile.getByRole('button', { name: '关闭', exact: true }).tap()
    check('closing drawer restores native dock', await mobile.evaluate(() => document.documentElement.dataset.dock === 'visible'))
    const slot = await mobile.evaluate(() => {
      const sc = document.querySelector('.amx-cal-tscroll'), r = sc.getBoundingClientRect()
      return { x: r.left + 40, y: Math.min(r.bottom, innerHeight) - 70, bottom: r.bottom }
    })
    await mobile.touchscreen.tap(slot.x, slot.y)
    await mobile.waitForTimeout(200)
    await mobile.screenshot({ path: path.join(OUT, 'phone-draft-observation.png') })
    await mobile.locator('.amx-cal-draftcard').waitFor()
    check('phone blank tap opens unsaved draft', (await rows(mobile)).length === 3)
    await mobile.getByRole('button', { name: '在此粘贴事件', exact: true }).tap()
    check('phone internal paste creates independent event with body', (await rows(mobile)).length === 4 && (await rows(mobile)).filter((x) => x.body).length === 2)
    await phone.close()
    check('no renderer exceptions on desktop or phone', errors.length === 0)
    fs.writeFileSync(path.join(OUT, 'result.json'), JSON.stringify({ passed: count, errors, phone: 'Chromium touch emulation; native chrome host stand-in' }, null, 2))
    console.log(`Artifacts: ${OUT}`)
  } finally { await browser.close(); await server.close() }
}
main().catch((e) => { console.error(e); process.exitCode = 1 })
