const pm = '.unified-body .ProseMirror'
const settle = p => p.waitForTimeout(250)
async function load(p, name, md) {
  await p.evaluate(({name,md}) => window.__upage.switchFile(name,md), {name,md})
  await settle(p)
}
async function select(p, text, caret = false) {
  return p.evaluate(({text,caret}) => {
    const v = window.__upage.probe.view(); let at = null
    v.state.doc.descendants((n,pos) => { if (at == null && n.isText && n.text.includes(text)) at = pos + n.text.indexOf(text) })
    if(at == null) throw Error('Missing text '+text)
    v.focus(); v.dispatch(v.state.tr.setSelection(v.state.selection.constructor.create(v.state.doc, at, caret ? at : at + text.length)))
  },{text,caret})
}
async function hover(p, selector) {
  const r = await p.locator(selector).first().boundingBox()
  await p.mouse.move(r.x+12,r.y+Math.min(10,r.height/2)); await settle(p)
}
