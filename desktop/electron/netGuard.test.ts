/**
 * SSRF 闸的判定表。这条通道是「渲染层给地址、主进程去请求」——
 * 任何一格判错都等于把本机 / 内网服务暴露给页面,所以逐段钉死。
 */
import { describe, expect, it } from 'vitest'
import { isPrivateIp } from './netGuard'

describe('isPrivateIp — 必须拒绝', () => {
  it.each([
    ['127.0.0.1', '回环'],
    ['127.1.2.3', '整个 127/8'],
    ['0.0.0.0', '本网'],
    ['10.0.0.5', '私网 A'],
    ['172.16.0.1', '私网 B 下界'],
    ['172.31.255.254', '私网 B 上界'],
    ['192.168.1.1', '私网 C'],
    ['169.254.169.254', '云元数据'],
    ['100.64.0.1', 'CGNAT'],
    ['224.0.0.1', '组播'],
    ['255.255.255.255', '广播'],
    ['::1', 'IPv6 回环'],
    ['::', 'IPv6 未指定'],
    ['fe80::1', 'IPv6 链路本地'],
    ['fd00::1', 'IPv6 唯一本地'],
    ['ff02::1', 'IPv6 组播'],
    ['::ffff:127.0.0.1', 'IPv4 映射回环'],
    ['::ffff:10.1.2.3', 'IPv4 映射私网'],
    ['::ffff:7f00:1', 'IPv4 映射回环·十六进制形(URL 规范化产物,曾绕过)'],
    ['::ffff:a9fe:a9fe', 'IPv4 映射云元数据·十六进制形'],
    ['::ffff:c0a8:101', 'IPv4 映射私网 C·十六进制形'],
    ['64:ff9b::7f00:1', 'NAT64 内嵌回环'],
    ['::7f00:1', 'v4-compatible 内嵌回环(废弃形态)'],
    ['not-an-ip', '非法值保守拒绝'],
    ['', '空串'],
  ])('%s (%s)', (ip) => {
    expect(isPrivateIp(ip)).toBe(true)
  })
})

describe('isPrivateIp — 必须放行', () => {
  it.each([
    ['1.1.1.1'],
    ['8.8.8.8'],
    ['142.250.72.14'], // calendar.google.com 一类
    ['172.15.255.255'], // 私网 B 之外
    ['172.32.0.1'], // 私网 B 之外
    ['192.167.1.1'], // 私网 C 之外
    ['100.63.255.255'], // CGNAT 之外
    ['100.128.0.1'], // CGNAT 之外
    ['169.253.0.1'], // 链路本地之外
    ['2001:4860:4860::8888'], // 公网 IPv6
    ['::ffff:808:808'], // IPv4 映射公网(8.8.8.8)十六进制形
    ['64:ff9b::101:101'], // NAT64 内嵌公网(1.1.1.1)
  ])('%s', (ip) => {
    expect(isPrivateIp(ip)).toBe(false)
  })
})
