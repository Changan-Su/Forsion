/** Real Electron, disk-discovered Bridge and byte-identical upstream packages. AI backend alone is stubbed.
 * npm run e2e:obsidianbridge; npm run demo:obsidianbridge leaves the isolated app open.
 */
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const electron = require('./lib/launch-electron.cjs')
const { startStubEngine } = require('./lib/stub-engine.cjs')
const ROOT = path.join(__dirname, '..')
const BASE = path.join(ROOT, 'prototypes/obsidian-bridge')
const ART = process.env.BRIDGE_ARTIFACTS || path.join(BASE, 'artifacts')
const DEMO = process.argv.includes('--demo')
const home = process.env.BRIDGE_HOME || fs.mkdtempSync(path.join(os.tmpdir(), 'forsion-obsidian-bridge-'))
const vault = path.join(home, 'vault')
const results = [], errors = []
function check(name, ok, detail) { results.push({ name, ok: !!ok, detail }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ' | ' + detail : ''}`) }
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
let app, win, frame, stub
async function boot() {
  app = await electron.launch({
    ...(process.env.STAGE_ELECTRON ? { executablePath: process.env.STAGE_ELECTRON } : {}),
    args: [`--user-data-dir=${path.join(home, 'userdata')}`, '--lang=zh-CN', ROOT], cwd: ROOT,
    env: { ...process.env, TANGU_HOME: home, TANGU_BACKEND_URL: stub.url, FORSION_WORKSPACE_DIR: path.join(home, 'workspace') },
  })
  win = await app.firstWindow()
  win.on('pageerror', e => { errors.push(String(e)); console.error('PAGEERROR', e.message) })
  await win.waitForSelector('#root', { timeout: 40000 })
  await win.waitForTimeout(1500)
  for (const label of ['跳过引导', 'Skip']) {
    const b = win.getByText(label, { exact: true }).first()
    if (await b.isVisible().catch(() => false)) { await b.click(); break }
  }
  await win.waitForSelector('.dv-groupview', { timeout: 30000 })
  // First boot registration is async. Use the real command palette to open the plugin view.
  await win.keyboard.press('Meta+k')
  await win.waitForTimeout(400)
  const input = win.locator('input').filter({ visible: true }).first()
  await input.fill('Obsidian Bridge')
  await win.waitForTimeout(500)
  await win.keyboard.press('Enter')
  await win.locator('iframe[title="Obsidian Bridge"]').waitFor({ timeout: 15000 })
  frame = await (await win.locator('iframe[title="Obsidian Bridge"]').elementHandle()).contentFrame()
  await frame.waitForFunction(() => !!window.bridge, { timeout: 20000 })
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows().find(w => !w.isDestroyed() && w.getTitle() !== ''); w?.setSize(1380, 940) })
}
async function shot(name) { await win.screenshot({ path: path.join(ART, name + '.png') }) }
async function click(action) { await frame.locator(`[data-action="${action}"]`).click() }
async function command(id) { await frame.locator(`[data-command="${id}"]`).click() }
async function text() { return frame.evaluate(() => window.bridge.editor.getValue()) }
async function main() {
  fs.mkdirSync(ART, { recursive: true }); fs.mkdirSync(vault, { recursive: true })
  const installed = path.join(home, 'plugins/forsion-plugin-obsidian-bridge')
  fs.cpSync(path.join(BASE, 'plugin'), installed, { recursive: true })
  fs.writeFileSync(path.join(vault, 'Original.md'), '# Original note\n\nThis must remain unchanged.\n')
  const originalHash = hash(path.join(vault, 'Original.md'))
  const ud = path.join(home, 'userdata-dev'); fs.mkdirSync(ud, { recursive: true })
  fs.writeFileSync(path.join(ud, 'amadeus-config.dev.json'), JSON.stringify({ lastVault: vault, localVault: vault }))
  fs.writeFileSync(path.join(ART, 'session.json'), JSON.stringify({ home, vault, installed }, null, 2))
  const receipts = JSON.parse(fs.readFileSync(path.join(installed, 'plugins/sources.json'), 'utf8'))
  for (const r of receipts) check(`${r.id} release assets unchanged`, r.files.every(f => hash(path.join(installed, 'plugins', r.id, f.name)) === f.sha256), r.version)
  stub = await startStubEngine({ sessions: [], messages: [], models: [] })
  await boot()
  const diag = await frame.evaluate(() => window.bridge.diagnostics())
  console.log('DIAGNOSTICS', JSON.stringify(diag))
  check('3 upstream packages loaded from nested directories', diag.plugins.length === 3 && diag.plugins.every(p => p.alive && !p.error))
  check('compatibility editor bound to isolated vault', path.resolve(diag.vaultKey) === path.resolve(vault), diag.vaultKey)
  await click('sort-sample')
  await command('obsidian-sort-and-permute-lines:sort-alphabetically')
  check('Sort and Permute sorts actual editor content', (await text()).trim() === 'Apple\nApple\nBanana\nZebra', JSON.stringify(await text()))
  await shot('01-sort')
  await command('obsidian-sort-and-permute-lines:permute-unique')
  check('Remove duplicates executes original plugin logic', (await text()).trim() === 'Apple\nBanana\nZebra')
  await click('undo')
  check('Command edits participate in editor undo', (await text()).includes('Apple\nApple'))
  await click('heading-sample')
  await command('obsidian-plugin-toc:create-toc')
  const toc = await text()
  check('Table of Contents inserts real heading links', toc.includes('[[#Introduction|Introduction]]') && toc.includes('[[#Method#Preparation|Preparation]]'), toc.slice(0, 350))
  await shot('02-toc')
  await click('heading-sample')
  await command('number-headings-obsidian:number-headings')
  const numbered = await text()
  check('Number Headings applies multi-change transaction', /## 1[. ]/.test(numbered) && /### 1\.2\.1/.test(numbered), numbered)
  await shot('03-numbered')
  const tocCard = frame.locator('[data-plugin="obsidian-plugin-toc"]')
  await tocCard.locator('[data-action="settings"]').click()
  await frame.getByLabel('Title', { exact: true }).fill('**Bridge contents**')
  await frame.evaluate(() => window.bridge.flush())
  await shot('04-settings')
  await click('close-settings')
  await click('heading-sample'); await command('obsidian-plugin-toc:create-toc')
  check('Original settings UI changes plugin behavior', (await text()).includes('**Bridge contents**'))
  await click('save-copy')
  await frame.waitForFunction(() => !!window.bridge.diagnostics().savedCopy)
  const copy = await frame.evaluate(() => window.bridge.diagnostics().savedCopy)
  check('Export persisted through real vault IPC', fs.readFileSync(path.join(vault, copy), 'utf8') === await text(), copy)
  check('Source note remains byte-identical', hash(path.join(vault, 'Original.md')) === originalHash)
  await click('open-saved')
  await win.locator('.ProseMirror').first().waitFor({ timeout: 15000 })
  check('Export opens in native Amadeus editor', (await win.locator('.ProseMirror').allTextContents()).join(' ').includes('Introduction'))
  await shot('08-native-note')
  await win.locator('.dv-tab').filter({ hasText: 'Obsidian Bridge' }).first().click()
  await win.locator('iframe[title="Obsidian Bridge"]').waitFor()
  frame = await (await win.locator('iframe[title="Obsidian Bridge"]').elementHandle()).contentFrame()
  await frame.waitForFunction(() => !!window.bridge)
  const badDir = path.join(installed, 'plugins/bridge-unsupported-probe')
  fs.mkdirSync(badDir)
  fs.writeFileSync(path.join(badDir, 'manifest.json'), JSON.stringify({ id: 'bridge-unsupported-probe', name: 'Unsupported API probe', version: '0.0.0' }))
  fs.writeFileSync(path.join(badDir, 'main.js'), "module.exports=class extends require('obsidian').Plugin { onload(){ require('fs') } }")
  await click('rescan')
  await frame.waitForFunction(() => window.bridge.diagnostics().plugins.some(p => p.id === 'bridge-unsupported-probe' && p.error))
  const bad = await frame.evaluate(() => window.bridge.diagnostics().plugins.find(p => p.id === 'bridge-unsupported-probe'))
  check('Unsupported dependency fails explicitly without stopping other plugins', !bad.alive && bad.error.includes('Unsupported external module: fs') && await frame.evaluate(() => window.bridge.diagnostics().plugins.filter(p => p.alive).length === 3))
  fs.rmSync(badDir, { recursive: true })
  await click('rescan')
  await frame.waitForFunction(() => window.bridge.diagnostics().plugins.length === 3 && window.bridge.diagnostics().plugins.every(p => p.alive))
  const numberCard = frame.locator('[data-plugin="number-headings-obsidian"]')
  await numberCard.locator('[data-action="toggle-plugin"]').click()
  const disabled = await frame.evaluate(() => window.bridge.diagnostics().plugins.find(p => p.id === 'number-headings-obsidian'))
  check('Disabling removes commands and interval', !disabled.alive && disabled.commands === 0 && disabled.timers === 0)
  const denied = await frame.evaluate(async () => { try { await window.bridge.run('number-headings-obsidian', 'number-headings'); return false } catch { return true } })
  check('Disabled command cannot mutate editor', denied)
  await frame.evaluate(() => window.bridge.flush())
  await app.close(); app = null
  await boot()
  const afterRestart = await frame.evaluate(() => window.bridge.diagnostics())
  check('Disabled state survives process restart', afterRestart.plugins.find(p => p.id === 'number-headings-obsidian')?.alive === false)
  await frame.locator('[data-plugin="obsidian-plugin-toc"] [data-action="settings"]').click()
  check('Plugin settings survive process restart', await frame.getByLabel('Title', { exact: true }).inputValue() === '**Bridge contents**')
  await click('close-settings')
  await frame.locator('[data-plugin="number-headings-obsidian"] [data-action="toggle-plugin"]').click()
  await click('heading-sample'); await command('number-headings-obsidian:number-headings')
  check('Re-enabled plugin operates after restart', /## 1[. ]/.test(await text()))
  await win.locator('#rb-mode, [data-ribbon-id="rb-mode"]').first().click()
  await frame.waitForFunction(() => document.documentElement.dataset.mode === 'dark')
  const dark = await frame.evaluate(() => ({ mode: document.documentElement.dataset.mode, bg: getComputedStyle(document.body).backgroundColor, text: getComputedStyle(document.body).color }))
  check('Real theme toggle reaches compatibility document', dark.mode === 'dark' && dark.bg !== 'rgb(247, 247, 248)', JSON.stringify(dark))
  await win.waitForTimeout(500); await shot('05-dark')
  await win.locator('#rb-mode, [data-ribbon-id="rb-mode"]').first().click()
  await frame.waitForFunction(() => document.documentElement.dataset.mode === 'light')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(860, 820))
  await win.waitForTimeout(400); await shot('06-narrow')
  check('Narrow layout has no horizontal page overflow', await frame.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1380, 940))
  await shot('07-ready')
  check('No uncaught renderer errors', errors.length === 0, errors.join('\n'))
  fs.writeFileSync(path.join(ART, 'results.json'), JSON.stringify({ results, errors, receipts, home }, null, 2))
  const failed = results.filter(x => !x.ok)
  console.log(`RESULT ${results.length - failed.length}/${results.length} passed; home=${home}`)
  if (failed.length) process.exitCode = 1
  if (DEMO && !failed.length) {
    console.log('DEMO_READY: close the isolated Electron window to stop the demo.')
    await new Promise(resolve => app.on('close', resolve))
  }
}
main().catch(async e => { console.error(e); results.push({ name: 'Harness completed', ok: false, detail: String(e) }); if (win) await shot('failure').catch(() => {}); fs.writeFileSync(path.join(ART, 'results.json'), JSON.stringify({ results, errors, home }, null, 2)); process.exitCode = 1 }).finally(async () => { if (app) await app.close().catch(() => {}); if (stub) await stub.close() })
