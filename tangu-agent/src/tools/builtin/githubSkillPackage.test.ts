import { afterEach, expect, it, vi } from 'vitest';
import { rm, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { configureTangu } from '../../seams/runtime.js';
import { createTanguProfile } from '../../profiles/index.js';
import { skillsProvider } from './skills.js';
import { memoryLogProvider } from './memoryLog.js';
import { loadSkillLoadout } from '../../services/skillLoadout.js';
import { getSessionDir } from '../../sandbox/sessionSandbox.js';

let root: string | undefined;
afterEach(async () => { if (root) await rm(root, { force: true, recursive: true }); });
it('an installed Word skill is discovered in a new cloud session and can execute its bundled Python script', async () => {
  const id = 'usr_gh_' + 'a'.repeat(64);
  const record = { id, name: 'Word formatting', content: 'Run scripts/check.py', description: 'Format a document' };
  const getSkillPackage = vi.fn(async () => ({ files: [{ path: 'scripts/check.py', base64: Buffer.from("print('format-ready')").toString('base64') }] }));
  const memory = { getMemory: vi.fn(async () => ({ content: 'Keep diagrams readable\n[Windows] Specific to Windows', updatedAt: null })) };
  const listSkills = vi.fn(async () => [record]);
  configureTangu({ profile: createTanguProfile({sandboxMode:'docker'}), brain: {assets: { listSkills, getSkill: async () => record, getSkillPackage }, memory }, host: {}, state: {} } as any);
  const loadout = await loadSkillLoadout('owner','tangu',{ execMode: 'sandbox', preset: 'work' });
  expect(listSkills).toHaveBeenCalledWith({ forUser: 'owner', visibleOnly: true });
  expect(loadout.enabledSkillIds).toContain(id);
  const ctx = { userId: 'owner', sessionId: randomUUID(), appId: 'tangu', execMode: 'sandbox', enabledSkillIds: [id] } as any;
  root = await getSessionDir(ctx);
  const result = String(await skillsProvider.tools()[0].execute({skill_id:id},ctx));
  expect(result).toContain(record.content);
  expect(await skillsProvider.tools()[0].execute({skill_id:id},ctx)).toEqual(result);
  expect(getSkillPackage).toHaveBeenCalledTimes(1);
  expect(getSkillPackage).toHaveBeenCalledWith('owner', id);
  const dir = /\/workspace\/(\.forsion-skill-[^\n]+)/.exec(result)![1];
  expect(await readFile(path.join(root,dir,'scripts/check.py'),'utf8')).toContain('format-ready');
  expect(execFileSync('python3', ['scripts/check.py'], { cwd: path.join(root,dir), encoding: 'utf8' }).trim()).toBe('format-ready');
  expect((await loadSkillLoadout('owner','tangu',{ execMode:'sandbox', skillsConfigured:true, enabledSkillIds: [] })).enabledSkillIds).toEqual([]);
  const remember = memoryLogProvider.tools().find(t => t.name === 'remember')!;
  expect(remember.definitionFor!(ctx).function.parameters.properties.action.enum).toEqual(['add','list']);
  expect(JSON.parse(String(await remember.execute({ action:'list', fact:null },ctx)))).toMatchObject({content:'Keep diagrams readable', supportedActions:['list','add']});
});
