/** CSV 生成的纯逻辑(RFC 4180)。多维表「导出 CSV」用;不认列/行,只认已经算好的字符串矩阵 ——
 *  「哪些列、哪些行、每格显示成什么」是渲染层的事(blocks/database/csvExport.ts)。
 *
 *  两条容易被忽略的正确性:
 *   1. **换行用 CRLF**:RFC 4180 如此,Excel 之外的老工具只认它;字段内部的换行原样保留在引号里。
 *   2. **公式注入防护**:CSV 打开在 Excel / Numbers / WPS 里,以 `=` `+` `-` `@` 开头的单元格会被当**公式**求值
 *      (`=1+1` 显示 2;`=cmd|'...'!A0` 这类 DDE 载荷更是历史上真出过事)。惯例是前置一个单引号让它变文本。
 *      ⚠️ 但 `-` `+` 必须**只在后面不是数字时**才防护 —— 否则每一个负数金额(`-1234.50`)都会变成文本,
 *      财务表导出即报废。`=` `@` 与制表/回车开头无条件防护(它们不可能是合法数值的开头)。 */

/** 需要防护的开头:`=` `@` 与制表符/回车(前导空白会被某些工具吃掉后暴露出后面的 `=`),
 *  以及 `+` `-` 但后面**不是**数字 / 小数点 / 货币符号(`\p{Sc}`:¥ $ € …)的情况。
 *
 *  两条豁免都是实打实踩出来的:
 *   - 数字豁免:不放行的话每个负数金额 `-1234.50` 都被前置成文本,财务表导出报废;
 *   - 货币豁免:本仓自己的数字格式化会产出 `-¥1,234.00元`。它对表格软件本来就是文本(带符号+单位),
 *     加 `'` 防不住任何东西,却会在 Excel 里**显示出那个单引号**(CSV 导入不吃 `'` 前缀那套输入法约定)。 */
const INJECT_RE = /^[=@\t\r]|^[+-](?![\d.\p{Sc}])/u

/** 单字段转义:先防注入,再按需加引号(字段含 `,` `"` CR LF 或**原值**前后带空白时必须加;内部 `"` 双写)。
 *  ⚠️ 前后空白按 `raw` 判,不按加过 `'` 的 s —— 否则 `\t=1+1` 这种「前导空白 + 危险起手」的字段
 *  在防护之后首字符成了 `'`,空白判据当场失效,前导制表符裸奔进 CSV。 */
export function csvField(raw: string): string {
  const src = raw ?? ''
  const s = INJECT_RE.test(src) ? `'${src}` : src
  const needQuote = /[",\r\n]/.test(s) || src !== src.trim()
  return needQuote ? `"${s.replace(/"/g, '""')}"` : s
}

/** 字符串矩阵 → CSV 文本(CRLF 分行,末尾带一个换行:多数工具对缺末行更挑剔)。
 *  **不带 BOM** —— BOM 是落盘/下载那一层的事(见 csvExport.withBom),纯函数保持干净好测。 */
export function toCsv(rows: string[][]): string {
  return rows.map((r) => r.map(csvField).join(',')).join('\r\n') + (rows.length ? '\r\n' : '')
}

/** Excel(Windows)靠 UTF-8 BOM 才认中文,没有它一律乱码。落盘与浏览器下载两条路都要加,
 *  所以单源在这里,别在两处各写一个 BOM 拼接。 */
export const withBom = (csv: string): string => `\uFEFF${csv}`
